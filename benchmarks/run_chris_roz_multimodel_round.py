class RoundGenerationError(RuntimeError):
    pass


def utc_now() -> str:
    return datetime.now(timezone.utc).isoformat().replace("+00:00", "Z")


def read_json(path: Path) -> Any:
    if not path.is_file():
        raise RoundGenerationError(f"Required JSON file is missing: {path}")
    return json.loads(path.read_text(encoding="utf-8"))


def write_json(path: Path, payload: Any) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = path.with_name(f".{path.name}.{os.getpid()}.{secrets.token_hex(3)}.tmp")
    temporary.write_text(json.dumps(payload, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    os.replace(temporary, path)


def sha256_file(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def sha256_value(value: Any) -> str:
    encoded = json.dumps(value, sort_keys=True, separators=(",", ":"), ensure_ascii=False).encode("utf-8")
    return hashlib.sha256(encoded).hexdigest()


def audio_metadata(path: Path) -> dict[str, Any]:
    info = sf.info(str(path))
    if info.frames <= 0 or info.samplerate <= 0:
        raise RoundGenerationError(f"Invalid generated audio: {path}")
    return {
        "duration_seconds": float(info.frames / info.samplerate),
        "sample_rate": int(info.samplerate),
        "channels": int(info.channels),
        "frames": int(info.frames),
    }


def peak_rss_gib() -> float:
    return resource.getrusage(resource.RUSAGE_SELF).ru_maxrss / (1024**3)


def fish_key() -> str:
    for name in ("FISH_API_KEY", "FISH_AUDIO_API_KEY"):
        value = str(os.environ.get(name) or "").strip()
        if value:
            return value
    result = subprocess.run(
        [
            "/usr/bin/security",
            "find-generic-password",
            "-s",
            FISH_KEYCHAIN_SERVICE,
            "-a",
            getpass.getuser(),
            "-w",
        ],
        capture_output=True,
        text=True,
        timeout=15,
        check=False,
    )
    value = result.stdout.strip()
    if result.returncode != 0 or not value:
        raise RoundGenerationError("Fish API key is unavailable in the environment or macOS Keychain.")
    return value


class FishClient:
    def __init__(self, api_key: str, model_header: str, max_attempts: int) -> None:
        self.api_key = api_key
        self.model_header = model_header
        self.max_attempts = max(1, int(max_attempts))
        self.session = requests.Session()

    @property
    def headers(self) -> dict[str, str]:
        return {"Authorization": f"Bearer {self.api_key}"}

    def _detail(self, response: requests.Response) -> str:
        try:
            payload = response.json()
            value = payload.get("message") or payload.get("detail") or payload.get("status")
            result = value if isinstance(value, str) else json.dumps(value, ensure_ascii=False)
        except Exception:
            result = response.text[:500]
        return str(result).replace(self.api_key, "[redacted]")

    def request(self, method: str, path: str, *, retryable: bool = True, **kwargs: Any) -> requests.Response:
        url = FISH_API_BASE + path
        headers = {**self.headers, **dict(kwargs.pop("headers", {}))}
        timeout = kwargs.pop("timeout", 240)
        for attempt in range(1, self.max_attempts + 1):
            try:
                response = self.session.request(method, url, headers=headers, timeout=timeout, **kwargs)
            except requests.RequestException as exc:
                if not retryable or attempt >= self.max_attempts:
                    raise RoundGenerationError(f"Fish network error: {type(exc).__name__}") from exc
                time.sleep(min(8.0, 0.75 * 2 ** (attempt - 1)))
                continue
            if response.status_code < 400:
                return response
            transient = response.status_code == 429 or response.status_code >= 500
            if retryable and transient and attempt < self.max_attempts:
                retry_after = response.headers.get("Retry-After")
                try:
                    delay = float(retry_after) if retry_after else 0.75 * 2 ** (attempt - 1)
                except ValueError:
                    delay = 0.75 * 2 ** (attempt - 1)
                time.sleep(min(15.0, max(0.25, delay)))
                continue
            raise RoundGenerationError(f"Fish HTTP {response.status_code}: {self._detail(response)}")
        raise RoundGenerationError(f"Fish request failed: {path}")

    def list_models(self, title: str) -> list[dict[str, Any]]:
        response = self.request(
            "GET",
            "/model",
            params={"self": "true", "title": title, "page_size": 100, "page_number": 1, "sort_by": "created_at"},
        )
        return [
            dict(item)
            for item in response.json().get("items", [])
            if isinstance(item, Mapping) and item.get("title") == title
        ]

    def create_model(self, title: str, reference: Path, transcript: str) -> dict[str, Any]:
        data: list[tuple[str, str]] = [
            ("type", "tts"),
            ("title", title),
            ("train_mode", "fast"),
            ("visibility", "private"),
            ("description", "Permitted Alexandria Chris/Roz blind evaluation reference."),
            ("enhance_audio_quality", "true"),
            ("generate_sample", "false"),
            ("tags", "alexandria-evaluation"),
            ("tags", "permitted-clone"),
            ("texts", transcript),
        ]
        content_type = "audio/wav"
        with reference.open("rb") as handle:
            response = self.request(
                "POST",
                "/model",
                data=data,
                files=[("voices", ("reference.wav", handle, content_type))],
                retryable=False,
                timeout=240,
            )
        payload = dict(response.json())
        if not str(payload.get("_id") or ""):
            raise RoundGenerationError(f"Fish returned no model ID for {title}.")
        return payload

    def synthesize(self, text: str, reference_id: str, settings: Mapping[str, Any]) -> bytes:
        response = self.request(
            "POST",
            "/v1/tts",
            headers={"Content-Type": "application/json", "model": self.model_header},
            json={
                "text": text,
                "reference_id": reference_id,
                "temperature": float(settings["temperature"]),
                "top_p": float(settings["top_p"]),
                "prosody": {"speed": 1.0, "volume": 0, "normalize_loudness": True},
                "normalize": True,
                "format": str(settings["format"]),
                "sample_rate": int(settings["sample_rate"]),
                "latency": str(settings["latency"]),
                "repetition_penalty": float(settings["repetition_penalty"]),
                "condition_on_previous_chunks": bool(settings["condition_on_previous_chunks"]),
                "chunk_length": 200,
                "max_new_tokens": 1024,
                "min_chunk_length": 50,
                "early_stop_threshold": 1,
            },
            timeout=300,
        )
        if len(response.content) < 512:
            raise RoundGenerationError(f"Fish returned only {len(response.content)} bytes.")
        return response.content


def sample_fingerprint(spec: Mapping[str, Any], model_contract: Mapping[str, Any]) -> str:
    return sha256_value(
        {
            "round_id": str(spec.get("round_id") or "alexandria_chris_roz_multimodel_round1_v1"),
            "spec": spec,
            "model_contract": model_contract,
        }
    )


def reusable(spec: Mapping[str, Any], evidence: Path, fingerprint: str) -> dict[str, Any] | None:
    audio = evidence / str(spec["output_file"])
    result = evidence / str(spec["result_file"])
    if not audio.is_file() or not result.is_file():
        return None
    try:
        record = read_json(result)
    except Exception:
        return None
    if record.get("sample_id") != spec["sample_id"]:
        return None
    if record.get("sample_fingerprint") != fingerprint:
        return None
    if record.get("audio_sha256") != sha256_file(audio):
        return None
    return record


def ensure_fish_models(
    client: FishClient,
    evidence: Path,
    specs: list[dict[str, Any]],
    model_contract: Mapping[str, Any],
) -> dict[str, dict[str, Any]]:
    state_path = evidence / "private/fish-voice-models.json"
    state = read_json(state_path) if state_path.is_file() else {
        "schema_version": 1,
        "round_id": "alexandria_chris_roz_multimodel_round1_v1",
        "models": {},
    }
    references = {spec["reference"]["reference_key"]: spec["reference"] for spec in specs}
    for key, reference in sorted(references.items()):
        fingerprint = sha256_value(
            {"reference_key": key, "audio_sha256": reference["audio_sha256"], "transcript_sha256": reference["transcript_sha256"]}
        )
        existing = state["models"].get(key)
        if isinstance(existing, Mapping) and existing.get("reference_fingerprint") == fingerprint and existing.get("model_id"):
            continue
        title = f"Alexandria {key} {fingerprint[:10]}"
        matches = client.list_models(title)
        if matches:
            remote = matches[-1]
        else:
            remote = client.create_model(
                title,
                evidence / reference["audio_file"],
                reference["transcript"],
            )
        state["models"][key] = {
            "model_id": str(remote["_id"]),
            "title": title,
            "visibility": "private",
            "reference_fingerprint": fingerprint,
            "reference_audio_sha256": reference["audio_sha256"],
            "reference_transcript_sha256": reference["transcript_sha256"],
            "created_or_verified_at": utc_now(),
        }
        write_json(state_path, state)
    return {key: dict(value) for key, value in state["models"].items()}


def generate_fish_cloud(evidence: Path, internal: Mapping[str, Any], smoke: bool) -> dict[str, Any]:
    specs = [spec for spec in internal["sample_specs"] if spec["model_key"] == "fish_s2_pro_cloud"]
    if smoke:
        specs = specs[:1]
    contract = next(row for row in internal["models"] if row["key"] == "fish_s2_pro_cloud")
    client = FishClient(fish_key(), str(contract["api_model_header"]), int(specs[0]["control"]["max_attempts"]))
    models = ensure_fish_models(client, evidence, specs, contract)
    complete = []
    for index, spec in enumerate(specs, start=1):
        fingerprint = sample_fingerprint(spec, contract)
        old = reusable(spec, evidence, fingerprint)
        if old is not None:
            complete.append(old)
            print(json.dumps({"model": "fish", "index": index, "count": len(specs), "sample": spec["sample_id"], "status": "reused"}), flush=True)
            continue
        output = evidence / spec["output_file"]
        output.parent.mkdir(parents=True, exist_ok=True)
        started = time.perf_counter()
        payload = client.synthesize(
            spec["fish_prompt"],
            models[spec["reference"]["reference_key"]]["model_id"],
            spec["control"],
        )
        partial = output.with_name(f".{output.name}.partial")
        partial.write_bytes(payload)
        os.replace(partial, output)
        metadata = audio_metadata(output)
        elapsed = time.perf_counter() - started
        record = {
            "schema_version": 1,
            "round_id": internal["round_id"],
            "sample_id": spec["sample_id"],
            "blind_id": spec["blind_id"],
            "sample_fingerprint": fingerprint,
            "model_key": spec["model_key"],
            "model_label": spec["model_label"],
            "identity_key": spec["identity_key"],
            "reference_tier": spec["reference_tier"],
            "style": spec["style"],
            "group": spec["group"],
            "repeat": spec["repeat"],
            "seed": spec["seed"],
            "reference_audio_sha256": spec["reference"]["audio_sha256"],
            "reference_transcript_sha256": spec["reference"]["transcript_sha256"],
            "target_text_sha256": spec["target_text_sha256"],
            "instruction_sha256": spec["instruction_sha256"],
            "prompt_sha256": spec["fish_prompt_sha256"],
            "control": spec["control"],
            "generation_seconds": elapsed,
            "real_time_factor": elapsed / metadata["duration_seconds"],
            "audio": metadata,
            "audio_sha256": sha256_file(output),
            "audio_file": spec["output_file"],
            "remote_voice_reference_key": spec["reference"]["reference_key"],
            "peak_rss_gib": peak_rss_gib(),
            "manual_listening_required": True,
            "production_promotion_allowed": False,
        }
        write_json(evidence / spec["result_file"], record)
        complete.append(record)
        print(json.dumps({"model": "fish", "index": index, "count": len(specs), "sample": spec["sample_id"], "rtf": record["real_time_factor"]}), flush=True)
        time.sleep(float(spec["control"].get("request_pause_seconds") or 0.0))
    return {"model": "fish_s2_pro_cloud", "complete": len(complete), "expected": len(specs)}


def generate_voxcpm2(evidence: Path, internal: Mapping[str, Any], smoke: bool) -> dict[str, Any]:
    specs = [spec for spec in internal["sample_specs"] if spec["model_key"] == "voxcpm2_controllable_clone"]
    if smoke:
        specs = specs[:1]
    contract = next(row for row in internal["models"] if row["key"] == "voxcpm2_controllable_clone")
    loaded, snapshots = load_requested_models("voxcpm2", specs)
    model = loaded["main"]
    complete = []
    try:
        import mlx.core as mx
        for index, spec in enumerate(specs, start=1):
            fingerprint = sample_fingerprint(spec, contract)
            old = reusable(spec, evidence, fingerprint)
            if old is not None:
                complete.append(old)
                print(json.dumps({"model": "voxcpm2", "index": index, "count": len(specs), "sample": spec["sample_id"], "status": "reused"}), flush=True)
                continue
            reference = evidence / spec["reference"]["audio_file"]
            adapter_sample = {
                "target_text": spec["target_text"],
                "control": spec["control"],
                "reference": {"conditioning_transcript": spec["reference"]["transcript"]},
            }
            mx.random.seed(int(spec["seed"]))
            started = time.perf_counter()
            audio, sample_rate = generate_voxcpm(model, adapter_sample, reference, evidence)
            elapsed = time.perf_counter() - started
            output = evidence / spec["output_file"]
            output.parent.mkdir(parents=True, exist_ok=True)
            sf.write(str(output), np.asarray(audio, dtype=np.float32), int(sample_rate), subtype="PCM_16")
            metadata = audio_metadata(output)
            record = {
                "schema_version": 1,
                "round_id": internal["round_id"],
                "sample_id": spec["sample_id"],
                "blind_id": spec["blind_id"],
                "sample_fingerprint": fingerprint,
                "model_key": spec["model_key"],
                "model_label": spec["model_label"],
                "model_snapshots": snapshots,
                "identity_key": spec["identity_key"],
                "reference_tier": spec["reference_tier"],
                "style": spec["style"],
                "group": spec["group"],
                "repeat": spec["repeat"],
                "seed": spec["seed"],
                "reference_audio_sha256": spec["reference"]["audio_sha256"],
                "reference_transcript_sha256": spec["reference"]["transcript_sha256"],
                "target_text_sha256": spec["target_text_sha256"],
                "instruction_sha256": spec["instruction_sha256"],
                "control": spec["control"],
                "generation_seconds": elapsed,
                "real_time_factor": elapsed / metadata["duration_seconds"],
                "audio": metadata,
                "audio_sha256": sha256_file(output),
                "audio_file": spec["output_file"],
                "peak_rss_gib": peak_rss_gib(),
                "manual_listening_required": True,
                "production_promotion_allowed": False,
            }
            write_json(evidence / spec["result_file"], record)
            complete.append(record)
            print(json.dumps({"model": "voxcpm2", "index": index, "count": len(specs), "sample": spec["sample_id"], "rtf": record["real_time_factor"]}), flush=True)
    finally:
        loaded.clear()
        try:
            import mlx.core as mx
            mx.clear_cache()
        except Exception:
            pass
    return {"model": "voxcpm2_controllable_clone", "complete": len(complete), "expected": len(specs)}


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--evidence-root", type=Path, default=DEFAULT_EVIDENCE)
    parser.add_argument("--model", choices=("fish", "voxcpm2"), required=True)
    parser.add_argument("--smoke", action="store_true")
    args = parser.parse_args()

    evidence = args.evidence_root.expanduser().resolve()
    internal = read_json(evidence / "private/internal-manifest.json")
    if internal.get("tnia_miller_included") is not False:
        raise RoundGenerationError("T'Nia must remain absent from generation.")
    if args.model == "fish":
        result = generate_fish_cloud(evidence, internal, args.smoke)
    else:
        result = generate_voxcpm2(evidence, internal, args.smoke)
    write_json(evidence / f"private/{result['model']}-generation-summary.json", {**result, "completed_at": utc_now(), "smoke": args.smoke})
    print(json.dumps(result, indent=2))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
